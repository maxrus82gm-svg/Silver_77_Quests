"""Guarded, explicit rollback. Default is read-only; never calls Git.

State is generated by validate_migration.py. Apply only on a saved, quiescent
copy after user/coordinator authorization. A multi-file rollback is resumable
by inspecting saved copies; it is not claimed to be a filesystem transaction.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat


def sha(data):
    return hashlib.sha256(data).hexdigest()


def safe(root, rel):
    p=root/rel
    if Path(rel).is_absolute() or '..' in Path(rel).parts:
        raise ValueError('unsafe relative rollback path')
    for q in [p,*p.parents]:
        if os.path.lexists(q):
            info=q.lstat()
            if stat.S_ISLNK(info.st_mode) or getattr(info,'st_file_attributes',0)&1024:
                raise ValueError('rollback link/reparse point')
    if not p.absolute().is_relative_to(root.absolute()):
        raise ValueError('rollback outside root')
    return p


def rollback(root, state, apply=False):
    root=Path(root).absolute()
    prepared=[]
    for row in state['files']:
        p=safe(root,row['path'])
        if not p.is_file() or sha(p.read_bytes())!=row['after_sha256']:
            raise ValueError('concurrent/user change; no rollback: '+row['path'])
        before=None
        if row['before_sha256']:
            before=safe(root,row['snapshot']).read_bytes()
            if sha(before)!=row['before_sha256']:
                raise ValueError('snapshot integrity failed')
        prepared.append((row,p,before))
    if not apply:
        return {'result':'ROLLBACK_DRY_RUN','writes':0,'files':len(prepared)}
    saved=safe(root,state['rollback_saved'])
    if saved.exists():
        raise ValueError('rollback evidence already exists; inspect before resume')
    saved.mkdir()
    # Preserve every changed/new candidate before removing or restoring any file.
    for row,p,before in prepared:
        target=saved/row['path'];target.parent.mkdir(parents=True,exist_ok=True)
        with target.open('xb') as f:f.write(p.read_bytes())
        if sha(target.read_bytes())!=row['after_sha256']:
            raise ValueError('rollback save readback failed; source not restored')
    for row,p,before in prepared:
        safe(root,row['path'])
        if sha(p.read_bytes())!=row['after_sha256']:
            raise ValueError('input changed during rollback; preserve evidence and reconcile')
        if before is None:p.unlink()
        else:p.write_bytes(before)
    return {'result':'ROLLED_BACK','files':len(prepared),'saved':str(saved)}


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',required=True)
    parser.add_argument('--state',required=True)
    parser.add_argument('--apply',action='store_true')
    args=parser.parse_args()
    try:
        root=Path(args.root).absolute();state_path=Path(args.state).absolute()
        state_path=safe(root,str(state_path.relative_to(root)))
        result=rollback(root,json.loads(state_path.read_text(encoding='utf-8')),args.apply)
        print(json.dumps(result,ensure_ascii=False));raise SystemExit(0)
    except (ValueError,OSError,KeyError) as e:
        print(json.dumps({'result':'ROLLBACK_BLOCKED','reason':str(e)},ensure_ascii=False))
        raise SystemExit(3)
